import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { rawCidV1 } from '../../../../scripts/ipfs/pin-raw-lib.mjs';
import { collections, pieces } from './art.mjs';

const require = createRequire(new URL('../../../../packages/cards/package.json', import.meta.url));
const { Resvg } = require('@resvg/resvg-js');
const kit = new URL('./', import.meta.url);
const json = value => `${JSON.stringify(value, null, 2)}\n`;
const contract = '../../../../packages/contracts/src/test-coins/JunkCollectionCatalog.sol';

export function generatedFiles() {
  const files = new Map();
  const rows = collections.map(c => ({ ...c, items: [] }));
  const manifest = { encoding: { imageSize: 512, imageFormat: 'png' }, files: [] };
  for (const { kind, variant, base, svg } of pieces()) {
    const png = new Resvg(svg, { font: { loadSystemFonts: false } }).render().asPng();
    assert.ok(png.length <= 1_048_576, 'picture exceeds one raw block');
    const sha256 = `0x${createHash('sha256').update(png).digest('hex')}`;
    files.set(`${base}.svg`, svg);
    files.set(`${base}.png`, png);
    rows[kind].items.push({ id: String(variant), path: `${base}.png`, sha256, cid: rawCidV1(sha256), bytes: png.length });
    manifest.files.push({ path: `${base}.png`, role: 'file', sha256 });
  }
  for (const row of rows) {
    files.set(`art/${row.key}/traits.json`, json(row.items.map(item => ({ id: item.id,
      attributes: [{ trait_type: 'Material', value: row.material }, { trait_type: 'Condition', value: item.id === '1' ? 'Worn' : 'Battered' }] }))));
  }
  files.set('catalog.json', json({ format: 'squarehole.test-junk-art/1', visibility: 'public', collections: rows }));
  files.set('pin-manifest.json', json(manifest));
  const select = (property) => rows.map((row, i) => `        if (kind == ${i}) return "${row[property]}";`).join('\n');
  files.set(contract, '// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n'
    + '// Generated by examples/boxes/junkyard/test-collections/build-art.mjs; public PNG SHA-256 digests.\n'
    + 'library JunkCollectionCatalog {\n'
    + `    function name(uint8 kind) internal pure returns (string memory) {\n${select('name')}\n        revert("collection kind");\n    }\n\n`
    + `    function symbol(uint8 kind) internal pure returns (string memory) {\n${select('symbol')}\n        revert("collection kind");\n    }\n\n`
    + '    function digest(uint8 kind, uint8 picture) internal pure returns (bytes32) {\n        require(picture == 1 || picture == 2, "picture");\n'
    + rows.map((row, i) => `        if (kind == ${i}) return picture == 1\n            ? bytes32(${row.items[0].sha256})\n            : bytes32(${row.items[1].sha256});`).join('\n')
    + '\n        revert("collection kind");\n    }\n}\n');
  return files;
}

export function checkArt() {
  for (const [path, expected] of generatedFiles()) {
    assert.deepEqual(readFileSync(new URL(path, kit)), Buffer.from(expected), `stale generated file: ${path}`);
  }
}
export function buildArt() {
  for (const [path, bytes] of generatedFiles()) {
    const destination = fileURLToPath(new URL(path, kit));
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, bytes);
  }
}
function isEntry() {
  try { return Boolean(process.argv[1]) && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href; } catch { return false; }
}
if (isEntry()) {
  try {
    const args = process.argv.slice(2);
    if (args.length === 0) buildArt();
    else if (args.length === 1 && args[0] === '--check') checkArt();
    else throw new Error('usage');
    process.stdout.write('10 public SVG/PNG pairs and Solidity digests verified.\n');
  } catch {
    process.stderr.write('Junk art refused; run build-art.mjs [--check] with the pinned renderer and reviewed files.\n');
    process.exitCode = 1;
  }
}
