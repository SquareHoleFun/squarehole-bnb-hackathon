import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { rawCidV1 } from '../../../../scripts/ipfs/pin-raw-lib.mjs';
import { TIERS, PICTURES, pieces, contactSheetSvg, logoSvg } from './art.mjs';

// The pinned renderer the Junkyard's test junk uses (packages/cards depends on it); no system fonts, no new dependency.
const require = createRequire(new URL('../../../../packages/cards/package.json', import.meta.url));
const { Resvg } = require('@resvg/resvg-js');
const kit = new URL('./', import.meta.url);
const json = value => `${JSON.stringify(value, null, 2)}\n`;
const contract = '../../../../packages/contracts/src/test-coins/TestTradingCardsCatalog.sol';
const render = svg => new Resvg(svg, { font: { loadSystemFonts: false } }).render().asPng();

export function generatedFiles() {
  const files = new Map();
  const rows = TIERS.map((t, tier) => ({ key: t.key, name: t.name, symbol: t.symbol, tier: String(tier), rarity: t.rarity, items: [] }));
  const manifest = { encoding: { imageSize: 700, imageFormat: 'png' }, files: [] };
  for (const { tier, picture, base, name, number, svg } of pieces()) {
    const png = render(svg);
    assert.ok(png.length <= 1_048_576, 'picture exceeds one raw block');
    const sha256 = `0x${createHash('sha256').update(png).digest('hex')}`;
    files.set(`${base}.svg`, svg);
    files.set(`${base}.png`, png);
    rows[tier].items.push({ id: String(picture), name, number: `${String(number).padStart(2, '0')}/16`, path: `${base}.png`, sha256, cid: rawCidV1(sha256), bytes: png.length });
    manifest.files.push({ path: `${base}.png`, role: 'file', sha256 });
  }
  for (const row of rows) {
    files.set(`art/${row.key}/traits.json`, json(row.items.map(item => ({ id: item.id,
      attributes: [{ trait_type: 'Rarity', value: row.rarity }, { trait_type: 'Card', value: item.name }, { trait_type: 'Number', value: item.number }] }))));
  }
  // TestTradingCards.pictureFor enforces this rule on chain: ids 1 to 4 are the four cards, ids 5 to 8 their second editions.
  files.set('catalog.json', json({ format: 'squarehole.test-card-art/1', visibility: 'public',
    pictureRule: 'token id n shows picture (n - 1) mod 4 + 1', collections: rows }));
  files.set('pin-manifest.json', json(manifest));
  files.set('contact-sheet.png', render(contactSheetSvg()));
  const logo = logoSvg();
  files.set('../art/logo.svg', logo);
  files.set('../art/logo.png', render(logo));
  const select = (fn) => rows.map((row, i) => `        if (tier == ${i}) return "${fn(row)}";`).join('\n');
  const perPicture = (fn) => rows.map((row, i) => `        if (tier == ${i}) {\n`
    + row.items.map((item, p) => `            if (picture == ${p + 1}) return ${fn(item)};`).join('\n') + '\n        }').join('\n');
  files.set(contract, '// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n'
    + '// Generated by examples/boxes/card-shop/test-cards/build-art.mjs; public PNG SHA-256 digests.\n'
    + 'library TestTradingCardsCatalog {\n'
    + `    uint8 internal constant PICTURES = ${PICTURES};\n\n`
    + `    function name(uint8 tier) internal pure returns (string memory) {\n${select(r => r.name)}\n        revert("card tier");\n    }\n\n`
    + `    function symbol(uint8 tier) internal pure returns (string memory) {\n${select(r => r.symbol)}\n        revert("card tier");\n    }\n\n`
    + `    function rarity(uint8 tier) internal pure returns (string memory) {\n${select(r => r.rarity)}\n        revert("card tier");\n    }\n\n`
    + `    function cardName(uint8 tier, uint8 picture) internal pure returns (string memory) {\n${perPicture(item => `"${item.name}"`)}\n        revert("card picture");\n    }\n\n`
    + `    function number(uint8 tier, uint8 picture) internal pure returns (string memory) {\n${perPicture(item => `"${item.number}"`)}\n        revert("card picture");\n    }\n\n`
    + `    function digest(uint8 tier, uint8 picture) internal pure returns (bytes32) {\n${perPicture(item => `bytes32(${item.sha256})`)}\n        revert("card picture");\n    }\n}\n`);
  return files;
}

export function checkArt() {
  for (const [path, expected] of generatedFiles()) {
    assert.deepEqual(readFileSync(new URL(path, kit)), Buffer.from(expected), `stale generated file: ${path}`);
  }
}
export function buildArt() {
  for (const [path, bytes] of generatedFiles()) {
    const destination = fileURLToPath(new URL(path, kit));
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, bytes);
  }
}
function isEntry() {
  try { return Boolean(process.argv[1]) && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href; } catch { return false; }
}
if (isEntry()) {
  try {
    const args = process.argv.slice(2);
    if (args.length === 0) buildArt();
    else if (args.length === 1 && args[0] === '--check') checkArt();
    else throw new Error('usage');
    process.stdout.write('16 public card SVG/PNG pairs, the contact sheet, the logo and Solidity digests verified.\n');
  } catch {
    process.stderr.write('Card art refused; run build-art.mjs [--check] with the pinned renderer and reviewed files.\n');
    process.exitCode = 1;
  }
}
