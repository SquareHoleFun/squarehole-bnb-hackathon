"""CQ11-0 / BC-003/067: independent reference amounts and admitted-raise properties."""
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[5]
spec = importlib.util.spec_from_file_location("launch_shape", ROOT / "packages/contracts/script-py/launch_shape.py")
shape = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shape)
K = shape.box_constants()
VECTORS = ROOT / "packages/box-spec/vectors/cases.v2.json"
SOLIDITY_VECTORS = Path(__file__).with_name("FullRangeVectors.sol")
MAX_RAISE = (1 << 128) - 1


def reference(c, q, t):
    """Pinned LiquidityAmounts floors, evaluated as unbounded rational integer arithmetic.

    Amount0's intermediate floor is intentional; add charges each amount rounded UP.
    Neither non-limiting liquidity is narrowed before taking the minimum.
    """
    a = shape.sqrt_price_at_tick(K["MIN_USABLE_TICK"])
    b = shape.sqrt_price_at_tick(K["MAX_USABLE_TICK"])
    p = c["sqrtPriceEndX96"]
    x, y = (t, q) if c["tIsCurrency0"] else (q, t)
    l = min(x * (p * b // shape.Q96) // (b - p), y * shape.Q96 // (p - a))
    ceil = lambda n, d: (n + d - 1) // d
    x_used = ceil(l * shape.Q96 * (b - p), b * p)
    y_used = ceil(l * (p - a), shape.Q96)
    q_used, t_used = (y_used, x_used) if c["tIsCurrency0"] else (x_used, y_used)
    return dict(tickLower=K["MIN_USABLE_TICK"], tickUpper=K["MAX_USABLE_TICK"], liquidity=l,
                qAmount=q_used, tAmount=t_used, qDust=q-q_used, tDust=t-t_used)


def admitted_near(r, order):
    """Choose a buildable neighbour by taking what a curve removal actually pays.

    Large raw raises can fall in NoExactLiquidity gaps. Walk down to the representable
    raise at the same centre (not a linear scan through millions of missing raw units).
    """
    try:
        return shape.box_curve(r, order, K)
    except ValueError as error:
        if not str(error).startswith("NoExactLiquidity"):
            raise
        centre = shape.centre_tick(r, order, K)[0]
        a, b = (shape.sqrt_price_at_tick(centre + d) for d in (-13440, 13440))
        l = shape.q_liquidity(a, b, r, order)
        return shape.box_curve(shape.q_amount(a, b, l, False, order), order, K)


def reference_vectors():
    rows = []
    # Includes every listing raise, 6/8/18-decimal examples, both ends, and CQ9's overflow boundary.
    raises = {1_000_000, 1_000_001, 1_510_000, 15_100_000, 43_368_085, 43_368_086, 43_368_087,
              4_206_980_085_000_000_000, MAX_RAISE}
    for listing in json.loads(VECTORS.read_text())["listings"]:
        raises.update(int(listing[key]) for key in ("raiseMin", "raiseMax"))
    for order in (False, True):
        for r in sorted(raises):
            c = admitted_near(r, order)
            for mode in ("pool-share", "p-limited", "t-limited", "p-gift", "zero-p", "zero-t", "dust"):
                q, t = {"pool-share": (c["raise"], c["poolShare"]),
                        "p-limited": (c["raise"] // 10, K["ISSUANCE"]),
                        "t-limited": (c["raise"], c["poolShare"] // 10),
                        "p-gift": (MAX_RAISE, K["ISSUANCE"]),
                        "zero-p": (0, c["poolShare"]), "zero-t": (c["raise"], 0),
                        "dust": (1, 1)}[mode]
                g = reference(c, q, t)
                rows.append(dict(name=f'{c["raise"]}/{order}/{mode}', raise_=str(c["raise"]),
                                 tIsCurrency0=order, qHeld=str(q), tAvailable=str(t),
                                 fullRange={key: value if key.startswith("tick") else str(value) for key, value in g.items()}))
    return [{("raise" if key == "raise_" else key): value for key, value in row.items()} for row in rows]


def vector_digest(rows):
    """sha256 chain of ABI words, including inputs, ticks, liquidity and debit/dust outputs."""
    digest = bytes(32)
    for row in rows:
        g = row["fullRange"]
        values = [row["raise"], row["tIsCurrency0"], row["qHeld"], row["tAvailable"],
                  g["tickLower"], g["tickUpper"], g["liquidity"], g["qAmount"], g["tAmount"], g["qDust"], g["tDust"]]
        digest = hashlib.sha256(digest + b"".join((int(v) % (1 << 256)).to_bytes(32, "big") for v in values)).digest()
    return digest.hex()


def solidity_fixture(rows):
    raises = [row["raise"] for row in rows if row["name"].endswith("/pool-share")]
    values = ",\n            ".join("uint256(" + r + ")" for r in raises)
    return f"""// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

// GENERATED by full_range_test.py --write-solidity-fixture from cases.v2.json.fullRangeLayouts.
// Python and TypeScript verify this digest and every input; Solidity replays the same 7 budgets
// for each curve, chaining sha256(abi.encode(previous, raise, order, q, t, FullRange fields)).
// This avoids granting test-time filesystem access outside the contracts root.
library FullRangeVectors {{
    bytes32 internal constant DIGEST = hex"{vector_digest(rows)}";

    function raises() internal pure returns (uint256[{len(raises)}] memory) {{
        return [
            {values}
        ];
    }}
}}
"""


class FullRangeTests(unittest.TestCase):
    def check_layout(self, c, q, t):
        g = shape.box_full_range(c, q, t, K)
        self.assertEqual(g, reference(c, q, t))
        self.assertLessEqual(g["qAmount"], q)
        self.assertLessEqual(g["tAmount"], t)
        self.assertEqual(g["qAmount"] + g["qDust"], q)
        self.assertEqual(g["tAmount"] + g["tDust"], t)
        self.assertLess(g["liquidity"], 1 << 128)

    def test_shared_reference_vectors(self):
        rows = json.loads(VECTORS.read_text())["fullRangeLayouts"]
        self.assertEqual(rows, reference_vectors(), "reference vectors stale")
        self.assertEqual(SOLIDITY_VECTORS.read_text(), solidity_fixture(rows))
        for row in rows:
            c = shape.box_curve(int(row["raise"]), row["tIsCurrency0"], K)
            self.check_layout(c, int(row["qHeld"]), int(row["tAvailable"]))

    def test_every_admitted_raise_property(self):
        # A property over the admitted domain, sampled at every bit scale. No claim
        # to enumerate 2^128 raises; each NoExactLiquidity hole is counted explicitly.
        seed = 0x43513131
        admitted = rejected = 0
        for i in range(2048):
            seed = (seed * 6364136223846793005 + 1442695040888963407) & MAX_RAISE
            r = 1_000_000 + seed % ((1 << (20 + i % 109)) - 1_000_000)
            for order in (False, True):
                try:
                    c = shape.box_curve(r, order, K)
                except ValueError as error:
                    self.assertTrue(str(error).startswith("NoExactLiquidity"))
                    rejected += 1
                    continue
                admitted += 1
                self.check_layout(c, r, c["poolShare"])
                self.check_layout(c, MAX_RAISE, K["ISSUANCE"])
        self.assertGreater(admitted, 1000)
        self.assertGreater(rejected, 0)
        print(f"CQ11 admitted-domain samples: {admitted} admitted, {rejected} exact-liquidity gaps")


if __name__ == "__main__":
    if sys.argv[1:] == ["--write-vectors"]:
        text = VECTORS.read_text()
        assert '"fullRangeLayouts"' not in text
        VECTORS.write_text(text.rstrip()[:-1] + ',\n  "fullRangeLayouts": ' + json.dumps(reference_vectors(), indent=2) + '\n}\n')
    elif sys.argv[1:] == ["--write-solidity-fixture"]:
        SOLIDITY_VECTORS.write_text(solidity_fixture(json.loads(VECTORS.read_text())["fullRangeLayouts"]))
    else:
        unittest.main()
