import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

// Independent bigint model. No Solidity/SDK arithmetic imports, FFI, RPC, or numeric amount conversions.
const ceil = (a, b) => a / b + (a % b === 0n ? 0n : 1n);
const presets = [100n, 500n, 2500n];
const traces = [];
for (const bps of presets) {
  let s = 100003n, e = 0n, n = 33n, entropy = 741n;
  const rows = [];
  for (let step = 0; step < 24; step++) {
    entropy = (entropy * 6364136223846793005n + 1442695040888963407n) & ((1n << 64n) - 1n);
    const returning = n < 33n && (entropy % 3n !== 0n || n === 1n);
    const k = 1n + entropy % (returning ? 33n - n : n - 1n);
    const p = returning ? (s - e) * k / n : ceil((s - e) * k, n);
    const f = ceil(p * (returning ? 500n : bps), 10000n);
    const nextE = returning ? e - p : e + p;
    const nextN = returning ? n + k : n - k;
    const ok = p >= k && p <= (returning ? e : s - e) && s - f >= nextE + nextN;
    const oldNumerator = e * n - (33n - n) * (s - e), oldN = n;
    if (ok) { s -= f; e = nextE; n = nextN; }
    const burn = (s - e - n) / 41n;
    s -= burn;
    const numerator = e * n - (33n - n) * (s - e);
    assert(n >= 1n && s >= e + n && numerator >= 0n);
    assert(numerator * oldN >= oldNumerator * n);
    rows.push([returning ? 1n : 0n, k, p, f, ok ? 1n : 0n, burn, s, e, n, numerator / n, numerator % n]);
  }
  traces.push({ preset: bps.toString(), initialSupply: '100003', count: '33', rows: rows.map(r => r.map(String)) });
}
const max = (1n << 256n) - 1n;
const wide = [1n, 3n, 9n].map(k => [max, 10n, k, ceil(max * k, 10n)].map(String));
const vector = { columns: ['returning', 'count', 'principal', 'fee', 'success', 'externalBurn', 'supply', 'escrow', 'inside', 'surplusFloor', 'surplusRemainder'], traces, wide };
const json = JSON.stringify(vector, null, 2) + '\n';
let sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

// Generated by script/existing-nfts/pricing-oracle.mjs; every amount originates in independent bigint math.
library SetPricingVectors {
    function trace(uint256 index) internal pure returns (uint256[11][] memory rows) {
        rows = new uint256[11][](24);
`;
for (let i = 0; i < traces.length; i++) {
  sol += `        ${i === 0 ? 'if' : 'else if'} (index == ${i}) {\n`;
  for (let j = 0; j < traces[i].rows.length; j++) sol += `            rows[${j}] = [uint256(${traces[i].rows[j][0]}), ${traces[i].rows[j].slice(1).join(', ')}];\n`;
  sol += '        }\n';
}
sol += '        else revert("vector index");\n    }\n';
sol += '    function wide() internal pure returns (uint256[4][] memory rows) {\n        rows = new uint256[4][](3);\n';
for (let i = 0; i < wide.length; i++) sol += `        rows[${i}] = [uint256(${wide[i][0]}), ${wide[i].slice(1).join(', ')}];\n`;
sol += '    }\n}\n';
const files = [
  [new URL('../../test/box-v2/existing-nfts/fixtures/pricing-vectors.json', import.meta.url), json],
  [new URL('../../test/box-v2/existing-nfts/SetPricingVectors.sol', import.meta.url), sol],
];
for (const [file, expected] of files) {
  if (process.argv.includes('--check')) assert.equal(readFileSync(file, 'utf8'), expected, 'stale pricing oracle vector');
  else writeFileSync(file, expected);
}
process.stdout.write(`Bigint oracle: ${traces.length * 24} operation steps and ${wide.length} full-width quotes verified.\n`);
