// Independent ABI oracle: deliberately does not import the SetSpec implementation.
// Regenerate: node packages/box-spec/vectors/set-v2/generate.mjs; verify: append --check.
import { readFileSync, writeFileSync } from 'node:fs';
import { encodeAbiParameters, keccak256, parseAbiParameters, stringToHex, zeroAddress, zeroHash } from 'viem';

const abi = parseAbiParameters('(uint16 format, bytes32 schema, bytes32 release, string tokenName, string tokenSymbol, (uint32 listingId, address token) pricing, uint256 raise, uint32 openAt, uint16 deadlineDays, uint256 creatorBuy, address collection, uint32 count, bytes32 setHash, uint16 pickFeeBps, string description, bytes32 logoSha256)');
const linkAbi = parseAbiParameters('address, uint256, uint8, bytes32');
const domains = Object.fromEntries([
  ['schema', 'SquareHole.SetSpecV2.v1'], ['release', 'SquareHole.ExistingNFTs.v1'],
  ['template', 'SquareHole.ExistingNFTs.PicksReturns.Grow.v1'],
].map(([key, value]) => [key, keccak256(stringToHex(value))]));
const collection = '0x1111111111111111111111111111111111111111';
const max = (1n << 256n) - 1n;
const vectors = [33, 10].map((count, vector) => {
  const ids = Array.from({ length: count }, (_, i) => i === 1 ? max : BigInt(i) ** 2n);
  const suffixes = Array(count + 1).fill(zeroHash);
  const links = Array(count);
  for (let i = count - 1; i >= 0; --i) {
    links[i] = encodeAbiParameters(linkAbi, [collection, ids[i], 0, suffixes[i + 1]]);
    suffixes[i] = keccak256(links[i]);
  }
  const pages = [];
  for (let start = 0; start < count; start += 32) {
    const end = Math.min(start + 32, count);
    pages.push({ collections: Array(end - start).fill(collection), ids: ids.slice(start, end), tiers: Array(end - start).fill(0), nextHash: suffixes[end] });
  }
  const pricing = vector === 0 ? { listingId: 0, token: zeroAddress } : { listingId: 42, token: '0x2222222222222222222222222222222222222222' };
  const spec = {
    format: 2, schema: domains.schema, release: domains.release,
    tokenName: vector === 0 ? 'Outside Set' : 'N'.repeat(32), tokenSymbol: vector === 0 ? 'SET' : 'S'.repeat(11),
    pricing, raise: vector === 0 ? 4206980085000000000n : max,
    openAt: vector === 0 ? 0 : 1794009600, deadlineDays: vector === 0 ? 30 : 180,
    creatorBuy: vector === 0 ? 0n : max - 1n, collection, count, setHash: suffixes[0],
    pickFeeBps: vector === 0 ? 500 : 2500,
    description: vector === 0 ? 'Named picks and returns' : 'D'.repeat(1024),
    logoSha256: `0x${'ab'.repeat(32)}`,
  };
  const context = { listing: { id: pricing.listingId, token: pricing.token, decimals: 18, class: 1, kind: 1, raise: spec.raise }, timestamp: 1792800000n };
  const encoded = encodeAbiParameters(abi, [spec]);
  return { name: vector === 0 ? 'sparse-native-32-plus-1' : 'listed-full-width-boundaries', spec, context, encoded, hash: keccak256(encoded), ids, links, suffixes, pages };
});
const json = JSON.stringify({ domains, vectors }, (_, value) => typeof value === 'bigint' ? value.toString() : value, 2) + '\n';
let sol = '// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n// GENERATED by packages/box-spec/vectors/set-v2/generate.mjs; checked against the shared JSON.\nlibrary SetVectors {\n';
for (const [method, type, expression] of [
  ['encoded', 'bytes memory', (v) => `hex"${v.encoded.slice(2)}"`],
  ['specHash', 'bytes32', (v) => v.hash],
  ['root', 'bytes32', (v) => v.suffixes[0]],
  ['suffix32', 'bytes32', (v) => v.suffixes[32] ?? zeroHash],
]) {
  sol += `    function ${method}(uint256 index) internal pure returns (${type}) {\n`;
  vectors.forEach((v, i) => { sol += `        if (index == ${i}) return ${expression(v)};\n`; });
  sol += '        revert("vector index");\n    }\n';
}
sol += '    function ids(uint256 index) internal pure returns (uint256[] memory result) {\n';
vectors.forEach((v, i) => {
  sol += `        if (index == ${i}) {\n            result = new uint256[](${v.ids.length});\n`;
  v.ids.forEach((id, j) => { sol += `            result[${j}] = ${id};\n`; });
  sol += '            return result;\n        }\n';
});
sol += '        revert("vector index");\n    }\n';
sol += '    function link(uint256 index) internal pure returns (bytes memory) {\n';
for (const i of [0, 1, 32]) sol += `        if (index == ${i}) return hex"${vectors[0].links[i].slice(2)}";\n`;
sol += '        revert("link index");\n    }\n}\n';
for (const [path, content] of [
  ['packages/box-spec/vectors/set-v2/vectors.json', json],
  ['packages/contracts/test/box-v2/existing-nfts/SetVectors.sol', sol],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`stale: ${path}`);
  } else writeFileSync(path, content);
}
