#!/usr/bin/env node
/** Offline authoring only. Dev startup serves committed bytes; it never generates or downloads pictures. */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodeAbiParameters } from 'viem';

// Reuse the repository's pinned rasterizer; no new dependency or network installation.
const { Resvg } = createRequire(new URL('../../../cards/package.json', import.meta.url))('@resvg/resvg-js');
const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../../../..');
const zero = `0x${'0'.repeat(64)}`;
const catalog = { schema: 'sh.local-art.v1', boxes: {} };
const sha256 = bytes => `0x${createHash('sha256').update(bytes).digest('hex')}`;

function save(file, bytes, source) {
  writeFileSync(join(directory, file), bytes);
  return { file, sha256: sha256(bytes), ...(source ? { source } : {}) };
}
const misfits = {};
for (const [role, source] of Object.entries({
  logo: 'packages/design/art/fit/fit-icon-512.png',
  cover: 'docs/design/misfits-v2/banner/final/misfits-collection-sorter-1024.png',
  banner: 'docs/design/misfits-v2/banner/final/misfits-banner-a-1600x400.png',
})) misfits[role] = save(`misfits-${role}.png`, readFileSync(join(root, source)), source);
misfits.spec = { coverSha256: misfits.logo.sha256, collectionCoverSha256: misfits.cover.sha256,
  addOns: [{ id: 6, params: encodeAbiParameters([{ type: 'bytes32' }, { type: 'bytes32[]' }, { type: 'string' }], [misfits.banner.sha256, [], '']) }] };
catalog.boxes.misfits = misfits;

// Simple hand-authored vector emblems. Different silhouettes and palettes also distinguish them without text.
const recipes = [
  ['plain', '#65d6b4', '<path d="M170 285h52v-58h52v-58h68v144H170z"/>'],
  ['holders', '#a99bff', '<circle cx="204" cy="219" r="34"/><circle cx="308" cy="219" r="34"/><path d="M152 316v-28q0-40 52-40t52 40q0-40 52-40t52 40v28z"/>'],
  ['shop', '#fbac76', '<path d="M166 181h180l22 60q-22 30-45 0-22 30-45 0-22 30-45 0-22 30-45 0-22 30-44 0zM172 259h168v79H172z"/><path d="M230 283h52v55h-52z" fill="#172234"/>'],
  ['failure', '#fc7c9c', '<path d="M256 153l112 188H144z"/><path d="M248 220h16v63h-16z" fill="#172234"/><circle cx="256" cy="308" r="10" fill="#172234"/>'],
  ['everyItem', '#77caff', '<rect x="166" y="166" width="78" height="78" rx="18"/><circle cx="307" cy="205" r="39"/><path d="M205 268l46 78h-92zM307 265l45 41-45 42-45-42z"/>'],
  ['coinPile', '#f9d979', '<ellipse cx="230" cy="320" rx="78" ry="24"/><path d="M152 286v34q78 49 156 0v-34z"/><ellipse cx="230" cy="286" rx="78" ry="24"/><path d="M204 220v40q78 49 156 0v-40z"/><ellipse cx="282" cy="220" rx="78" ry="24"/>'],
  ['usdc', '#86b8ff', '<circle cx="256" cy="256" r="94" fill="none" stroke="currentColor" stroke-width="18"/><path d="M299 204h-61q-42 0-42 31t60 30q60 0 60 31t-42 31h-61M256 178v170" fill="none" stroke="currentColor" stroke-width="16" stroke-linecap="round"/>'],
  ['stock', '#b9eb85', '<path d="M163 279h43v68h-43zM235 235h43v112h-43zM307 186h43v161h-43z"/><path d="M160 237l75-64 39 24 75-58" fill="none" stroke="currentColor" stroke-width="13"/>'],
  ['gold', '#ffc46e', '<path d="M200 177h112l53 81-109 96-109-96z"/><path d="M200 177l56 177 56-177M147 258h218" fill="none" stroke="#172234" stroke-width="10"/>'],
];
for (const [mode, [name, color, emblem]] of recipes.entries()) {
  const box = { mode };
  for (const [role, size] of [['logo', 512], ['cover', 1024]]) {
    const background = role === 'cover'
      ? `<path d="M0 380L512 110v402H0z" fill="${color}" opacity=".09"/><circle cx="440" cy="64" r="174" fill="${color}" opacity=".08"/><path d="M36 432h440M36 448h280" stroke="${color}" opacity=".3" stroke-width="2"/>`
      : '';
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 512 512"><rect width="512" height="512" fill="#101b2b"/>${background}<circle cx="256" cy="256" r="159" fill="#172234" stroke="${color}" stroke-opacity=".4" stroke-width="2"/><g fill="${color}" color="${color}">${emblem}</g></svg>`;
    box[role] = save(`${name}-${role}.png`, new Resvg(svg).render().asPng());
  }
  // TOKEN_ONLY, SHOP and PILE require a zero collection cover. Their logo is their on-chain card cover too.
  box.spec = { coverSha256: box.logo.sha256, collectionCoverSha256: mode === 4 ? box.cover.sha256 : zero };
  catalog.boxes[name] = box;
}
writeFileSync(join(directory, 'catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);
const cases = recipes.map(([name], mode) => `        if (mode == ${mode}) return ${catalog.boxes[name].logo.sha256};`).join('\n');
writeFileSync(join(root, 'packages/contracts/script/local/LocalBoxArt.sol'), `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

// Generated by packages/chain/scripts/local-art/generate.mjs from committed local PNG bytes.
// Local specs only. No production box-0 spec, ABI or contract is changed.
library LocalBoxArt {
    bytes32 internal constant MISFITS_LOGO = ${misfits.logo.sha256};
    bytes32 internal constant MISFITS_COVER = ${misfits.cover.sha256};
    bytes32 internal constant MISFITS_BANNER = ${misfits.banner.sha256};
    bytes32 internal constant ITEMS_COVER = ${catalog.boxes.everyItem.cover.sha256};

    /// @notice Script/test callers read the fixed local logo commitment; this moves no funds.
    function logo(uint8 mode) internal pure returns (bytes32) {
${cases}
        revert("unknown local art recipe");
    }
}
`);
console.warn('Committed-art inputs written: 9 local logo/cover pairs, 3 exact Misfits files, catalog and Solidity hashes.');
