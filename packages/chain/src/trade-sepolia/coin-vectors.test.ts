import { readFileSync, writeFileSync } from 'node:fs';
import { decodeFunctionData, encodeFunctionResult, encodeFunctionData, keccak256, toHex, zeroAddress, type Address, type Hex } from 'viem';
import { expect, it } from 'vitest';
import type { Eip1193Request } from '../write/eip1193';
import { COIN_ABI, TRADE_ABI, decodeTradeRevert, prepareFaucetSepolia, preparePairSwapSepolia } from './index';
import { required, USER, POOL, MANAGER, CODE } from './test-support';

const dir = new URL('../../../contracts/test/box-v2/sepolia-all/fixtures/', import.meta.url);
interface State {
  name: string; teth: Address; coin: Address; amount: string; input: string; output: string; afterPrice: string;
  storage: Record<string, string>;
}
it('CC-6 prepares bytes from eight real alpha states, with exact independently executed output and price', async () => {
  const states = JSON.parse(readFileSync(new URL('coin-state.json', dir), 'utf8')) as State[];
  expect(states).toHaveLength(8);
  const swaps: string[] = [], approvals: string[] = [];
  let drip = '';
  for (const state of states) {
    const amount = BigInt(state.amount), forward = BigInt(state.name) % 2n === 0n;
    const input = forward ? state.teth : state.coin, output = forward ? state.coin : state.teth;
    const zeroForOne = BigInt(input) < BigInt(output);
    const deployment = { chainId: 31337, status: 'deployed', teth: { address: state.teth, codeHash: keccak256(CODE) },
      pairHelper: { address: '0x0000000000000000000000000000000000000012', codeHash: keccak256(CODE) },
      poolSwapTest: POOL, poolManager: MANAGER, poolSwapTestCodeHash: keccak256(CODE),
      pairs: [{ coin: state.coin, symbol: 'fixture', decimals: 18, fee: '3000', tickSpacing: 60, hooks: zeroAddress, tickLower: -887220, tickUpper: 887220 }] };
    const rpc: Eip1193Request = async r => {
      if (r.method === 'eth_chainId') return '0x7a69';
      if (r.method === 'eth_getBlockByNumber') return { number: '0x10', hash: `0x${'ab'.repeat(32)}`, timestamp: '0x3e8', transactions: [] };
      if (r.method === 'eth_getCode') return CODE;
      if (r.method === 'eth_estimateGas') return '0x74642';
      if (r.method !== 'eth_call') throw new Error(r.method);
      expect((r.params as unknown[])[1]).toBe('0x10');
      const d = decodeFunctionData({ abi: [...COIN_ABI, ...TRADE_ABI], data: (r.params as [{ data: Hex }])[0].data });
      const d0 = zeroForOne ? -BigInt(state.input) : BigInt(state.output);
      const d1 = zeroForOne ? BigInt(state.output) : -BigInt(state.input);
      const values: Record<string, unknown> = { manager: MANAGER, allowance: amount, balanceOf: amount,
        open: false, admitted: true, nextDripAt: 0n, dailyRemaining: 10n ** 18n,
        swap: BigInt.asIntN(256, BigInt.asUintN(128, d0) << 128n | BigInt.asUintN(128, d1)) };
      if (d.functionName === 'drip') return '0x';
      if (d.functionName === 'extsload') values.extsload = toHex(BigInt(required(state.storage[d.args[0]])), { size: 32 });
      return encodeFunctionResult({ abi: [...COIN_ABI, ...TRADE_ABI], functionName: d.functionName, result: values[d.functionName] as never });
    };
    const options = { rpc, chainId: 31337, from: USER, localDeployment: deployment } as const;
    const result = await preparePairSwapSepolia({ ...options, input, output, amountIn: amount });
    if (!result.ok) throw new Error(`${state.name}: ${result.reason}`);
    expect(result.plan.expectedInput).toBe(amount);
    expect(result.plan.expectedOutput).toBe(BigInt(state.output));
    expect(result.plan.expectedSqrtPriceX96).toBe(BigInt(state.afterPrice));
    swaps.push(`        if (id == ${state.name}) { data = hex"${required(result.plan.call).data.slice(2)}"; output = ${state.output}; price = ${state.afterPrice}; }`);
    approvals.push(`        if (id == ${state.name}) data = hex"${required(result.plan.approvals.at(-1)).data.slice(2)}";`);
    const faucet = await prepareFaucetSepolia(options);
    if (!faucet.ok) throw new Error(faucet.reason);
    drip = required(faucet.plan.call).data.slice(2);
  }
  const source = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;
// Generated by trade-sepolia/coin-vectors.test.ts from real 31337 alpha state. Only addresses relocate.
import {PoolKey} from "v4-core/src/types/PoolKey.sol";
import {Currency} from "v4-core/src/types/Currency.sol";
library CoinVectors {
    function swap(uint256 id, PoolKey memory key) internal pure returns (bytes memory data, uint256 output, uint160 price) {
${swaps.join('\n')}
        require(data.length > 0, "unknown vector");
        word(data, 0, uint160(Currency.unwrap(key.currency0))); word(data, 1, uint160(Currency.unwrap(key.currency1)));
    }
    function approval(uint256 id, address spender, bool reset) internal pure returns (bytes memory data) {
${approvals.join('\n')}
        require(data.length > 0, "unknown vector"); word(data, 0, uint160(spender));
        if (reset) word(data, 1, 0);
    }
    function drip() internal pure returns (bytes memory) { return hex"${drip}"; }
    function word(bytes memory data, uint256 index, uint256 value) private pure {
        assembly ("memory-safe") { mstore(add(add(data, 36), mul(index, 32)), value) }
    }
}
`;
  const path = new URL('CoinVectors.sol', dir);
  if (process.env.SH_WRITE_COIN_VECTORS === '1') writeFileSync(path, source);
  expect(readFileSync(path, 'utf8')).toBe(source);
  expect(`0x${drip}`).toBe(encodeFunctionData({ abi: COIN_ABI, functionName: 'drip' }));
});
it('CC-4 decodes the actual failed contract calls, including cooldown time', () => {
  const errors = JSON.parse(readFileSync(new URL('coin-errors.json', dir), 'utf8')) as { reason: string; data: Hex }[];
  expect(errors.map(e => e.reason)).toEqual(['not_admitted', 'cooldown_active', 'insufficient_allowance', 'insufficient_balance', 'daily_cap_reached', 'insufficient_allowance', 'insufficient_balance']);
  for (const e of errors) expect(decodeTradeRevert(e.data)).toBe(e.reason);
});
