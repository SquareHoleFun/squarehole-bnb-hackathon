import { readFileSync, writeFileSync } from 'node:fs';
import { encodeErrorResult, zeroAddress } from 'viem';
import { expect, it } from 'vitest';
import { TRADE_ERRORS } from './abi';
import { decodeTradeRevert } from './revert';
import { required, fixture, capturedFixture, type CapturedPoolState, COIN, HOOK, ROUTER, USER } from './test-support';

const dir = new URL('../../../contracts/test/box-v2/sepolia-all/fixtures/', import.meta.url);

it('SH-ALPHA-TRADE-CALLS: Solidity executes the exact builder bytes (only deployment addresses/time relocated)', async () => {
  const inputs = JSON.parse(readFileSync(new URL('inputs.json', dir), 'utf8')) as Record<string, { raise: string; amount: string; quote?: string; spot?: string }>;
  const poolStates = JSON.parse(readFileSync(new URL('pool-state.json', dir), 'utf8')) as Record<string, CapturedPoolState>;
  const poolPlans: Record<string, { output: bigint; price: bigint }> = {};
  const vectors: Record<string, string> = {};
  let approval = '';
  let revoke = '';
  for (const [name, input] of Object.entries(inputs)) {
    const window = name.startsWith('window');
    const amount = BigInt(input.amount);
    const f = !window ? capturedFixture(required(poolStates[name]), !name.endsWith('Sell'), name === 'graduatedSell') : fixture({ phase: window ? 2 : name === 'graduatedSell' ? 5 : 3,
      p: name === 'windowErc20' ? COIN : zeroAddress, allowance: amount, raise: BigInt(input.raise),
      ...(input.quote ? { output: BigInt(input.quote) } : {}), ...(input.spot ? { spot: BigInt(input.spot) } : {}) });
    const result = await f.prepare(name.endsWith('Sell') ? 'sell' : 'buy', amount);
    if (!result.ok || !result.plan.call) throw new Error(`invalid vector ${name}`);
    if (!window) {
      const actual = required(poolStates[name]);
      expect(result.plan.expectedOutput).toBe(BigInt(actual.output));
      expect(result.plan.expectedSqrtPriceX96).toBe(BigInt(actual.afterPrice));
      poolPlans[name] = { output: required(result.plan.expectedOutput), price: required(result.plan.expectedSqrtPriceX96) };
    }
    vectors[name] = result.plan.call.data.slice(2);
    if (name === 'windowErc20') { approval = required(result.plan.approvals[0]).data.slice(2); revoke = required(result.plan.revoke).data.slice(2); }
  }
  const errorCases = [
    ['BuyThroughLaunchRouter', [ROUTER, 1384n], 'buy_through_launch_router'], ['CurveIsClosed', [16n], 'curve_closed'],
    ['CurveIsClosed', [], 'curve_closed'], ['TradingNotOpen', [1000n], 'trading_not_open'], ['FailurePending', [2000n], 'failure_pending'],
    ['BelowCurveFloor', [123n], 'below_curve_floor'], ['UnknownPool', [], 'unknown_pool'], ['NotOpen', [1000n], 'not_open'],
    ['WindowClosed', [1384n], 'window_closed'], ['Expired', [1120n], 'expired'], ['WrongValue', [0n, 100n], 'wrong_value'],
    ['InsufficientOutput', [1n, 2n], 'insufficient_output'], ['AmountTooSmall', [], 'amount_too_small'], ['RecipientRefused', [USER], 'recipient_refused'],
  ] as const;
  const errors = errorCases.map(([name, args, reason]) => {
    const data = encodeErrorResult({ abi: TRADE_ERRORS, errorName: name, args: args as never });
    expect(decodeTradeRevert(data)).toBe(reason);
    return data;
  });
  errors.push(encodeErrorResult({ abi: TRADE_ERRORS, errorName: 'WrappedError', args: [HOOK, '0x12345678', required(errors[0]), '0xdeadbeef'] }));
  expect(decodeTradeRevert(errors.at(-1))).toBe('buy_through_launch_router');
  const source = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;
// Generated by packages/chain/src/trade-sepolia/vectors.test.ts; do not edit.
// Inputs are raw decimal strings captured from BuyHelper's local contracts. Only addresses and block time relocate.
import {PoolKey} from "v4-core/src/types/PoolKey.sol";
import {Currency} from "v4-core/src/types/Currency.sol";
library TradeVectors {
    function windowBuy(bool erc20, address recipient, uint256 deadline) internal pure returns (bytes memory data) {
        if (erc20) data = hex"${vectors.windowErc20}"; else data = hex"${vectors.windowEth}";
        word(data, 2, uint160(recipient)); word(data, 3, deadline);
    }
    function pool(PoolKey memory key, bool buy, bool graduated) internal pure returns (bytes memory data) {
        if (buy) data = hex"${vectors.bondingBuy}"; else if (graduated) data = hex"${vectors.graduatedSell}"; else data = hex"${vectors.bondingSell}";
        word(data, 0, uint160(Currency.unwrap(key.currency0)));
        word(data, 1, uint160(Currency.unwrap(key.currency1))); word(data, 4, uint160(address(key.hooks)));
    }
    function expectedPool(bool buy, bool graduated) internal pure returns (uint256 output, uint160 price) {
        if (buy) return (${poolPlans.bondingBuy?.output}, ${poolPlans.bondingBuy?.price});
        if (graduated) return (${poolPlans.graduatedSell?.output}, ${poolPlans.graduatedSell?.price});
        return (${poolPlans.bondingSell?.output}, ${poolPlans.bondingSell?.price});
    }
    function approval(address spender, bool reset) internal pure returns (bytes memory data) {
        if (reset) data = hex"${revoke}"; else data = hex"${approval}";
        word(data, 0, uint160(spender));
    }
    function revertData(uint256 id) internal pure returns (bytes memory) {
${errors.map((data, i) => `        if (id == ${i}) return hex"${data.slice(2)}";`).join('\n')}
        revert("unknown fixture");
    }
    function word(bytes memory data, uint256 index, uint256 value) private pure {
        assembly ("memory-safe") { mstore(add(add(data, 36), mul(index, 32)), value) }
    }
}
`;
  const path = new URL('TradeVectors.sol', dir);
  if (process.env.SH_WRITE_TRADE_VECTORS === '1') writeFileSync(path, source);
  expect(readFileSync(path, 'utf8')).toBe(source);
});

it('real curve plans fill 1%, 10%, 50% and a sell with exact output and post-trade price', async () => {
  const states = JSON.parse(readFileSync(new URL('pool-state.json', dir), 'utf8')) as Record<string, CapturedPoolState>;
  const branches: string[] = [];
  for (const id of ['0', '1', '2', '3']) {
    const input = required(states[id]);
    const result = await capturedFixture(input, id !== '3').prepare();
    if (!result.ok) throw new Error(result.reason);
    expect(result.plan.expectedInput).toBe(BigInt(input.amount));
    expect(result.plan.expectedOutput).toBe(BigInt(input.output));
    expect(result.plan.expectedSqrtPriceX96).toBe(BigInt(input.afterPrice));
    expect(result.plan.warning).toContain('partially');
    branches.push(`        if (id == ${id}) { data = hex"${required(result.plan.call).data.slice(2)}"; output = ${result.plan.expectedOutput}; price = ${result.plan.expectedSqrtPriceX96}; }`);
  }
  const source = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;
// Generated by trade-sepolia/vectors.test.ts from executed local v4 state. Only addresses relocate.
import {PoolKey} from "v4-core/src/types/PoolKey.sol";
import {Currency} from "v4-core/src/types/Currency.sol";
library Af2Vectors {
    function get(uint256 id, PoolKey memory key) internal pure returns (bytes memory data, uint256 output, uint160 price) {
${branches.join('\n')}
        require(data.length > 0, "unknown vector");
        word(data, 0, uint160(Currency.unwrap(key.currency0)));
        word(data, 1, uint160(Currency.unwrap(key.currency1))); word(data, 4, uint160(address(key.hooks)));
    }
    function word(bytes memory data, uint256 index, uint256 value) private pure {
        assembly ("memory-safe") { mstore(add(add(data, 36), mul(index, 32)), value) }
    }
}
`;
  const path = new URL('Af2Vectors.sol', dir);
  if (process.env.SH_WRITE_TRADE_VECTORS === '1') writeFileSync(path, source);
  expect(readFileSync(path, 'utf8')).toBe(source);
});
