// Deterministic local ABI generation. Never reads or writes the frozen core/v2 ABI.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('usage: regenerate-abi-set-v2.mjs [--check]');
const target = new URL('./abi-set-v2.ts', import.meta.url);
const cwd = fileURLToPath(new URL('../../../../contracts/', import.meta.url));
const shapes = [
  ['setFactoryV2Abi', 'set/SetFactoryV2.sol:SetFactoryV2'],
  ['setVaultV2Abi', 'set/SetVaultV2.sol:SetVaultV2'],
  ['setRegistryV2Abi', 'interfaces/IBoxRegistryV2.sol:IBoxRegistryV2'],
  ['setStarterSetLoaderV2Abi', 'StarterSetLoaderV2.sol:StarterSetLoaderV2'],
  ['setCoordinatorV2Abi', 'interfaces/IBoxCoordinatorV2.sol:IBoxCoordinatorV2'],
  ['setTokenV2Abi', 'BoxTokenV2.sol:BoxTokenV2'],
  ['setLaunchRouterV2Abi', 'interfaces/IBoxPeripheryV2.sol:IBoxLaunchRouterV2'],
  ['setListingRegistryV2Abi', 'interfaces/IListingRegistry.sol:IListingRegistry'],
];
let generated = '// Generated by regenerate-abi-set-v2.mjs with forge inspect --offline (solc 0.8.26).\n';
for (const [name, source] of shapes) {
  const abi = JSON.parse(execFileSync('forge', ['inspect', `src/box-v2/${source}`, 'abi', '--json', '--offline'], { cwd, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }));
  generated += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) {
    console.error('abi-set-v2.ts is stale; run node packages/chain/src/core/set-v2/regenerate-abi-set-v2.mjs');
    process.exitCode = 1;
  } else process.stdout.write('Set ABIs match offline forge output.\n');
} else {
  writeFileSync(target, generated);
  process.stdout.write('Generated set ABIs from offline forge output.\n');
}
