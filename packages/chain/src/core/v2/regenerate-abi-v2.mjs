// Run from any directory. forge inspect uses only the pinned local compiler/dependencies.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = new URL('./abi-v2.ts', import.meta.url);
const cwd = fileURLToPath(new URL('../../../../contracts/', import.meta.url));
const shapes = [
  ['royaltyRouterV2Abi', 'IBoxPeripheryV2.sol:IBoxRoyaltyRouterV2'],
  ['receiverShopV21Abi', 'IBoxReceiverShopV21.sol:IBoxReceiverShopV21'],
  ['receiverModulesV21Abi', 'IFeeModulesV21.sol:IFeeModulesV21'],
  ['feeActionV21Abi', 'IFeeModulesV21.sol:IFeeActionV21'],
  ['registryV2Abi', 'IBoxRegistryV2.sol:IBoxRegistryV2'],
  ['receiverPayInTV21Abi', 'IBoxReceiverPayInTV21.sol:IBoxReceiverPayInTV21'],
  ['receiverPileV21Abi', 'IBoxReceiverPileV21.sol:IBoxReceiverPileV21'],
  ['receiverEatV21Abi', 'IBoxReceiverEatV21.sol:IBoxReceiverEatV21'],
  ['listingBurnV21Abi', 'IListingBurnV21.sol:IListingBurnV21'],
  ['listingRegistryV2Abi', 'IListingRegistry.sol:IListingRegistry'],
  ['coordinatorV2Abi', 'IBoxCoordinatorV2.sol:IBoxCoordinatorV2'],
  ['factoryV2Abi', 'IBoxCoordinatorV2.sol:IBoxFactoryV2'],
  ['hookV2Abi', 'IBoxHookV2.sol:IBoxHookV2'],
  ['holderBatchNoticeV2Abi', 'IBoxHookV2.sol:IBoxHolderBatchNoticeV2'],
  ['receiverV2Abi', 'IBoxReceiverV2.sol:IBoxReceiverV2'],
  ['receiverItemsV2Abi', 'IBoxReceiverV2.sol:IBoxReceiverItemsV2'],
  ['vaultItemsV2Abi', 'IBoxVaultV2.sol:IBoxVaultItemsV2'],
  ['factoryPileV2Abi', 'IBoxCoordinatorV2.sol:IBoxFactoryPileV2'],
  ['vaultV2Abi', 'IBoxVaultV2.sol:IBoxVaultV2'],
  ['launchRouterV2Abi', 'IBoxPeripheryV2.sol:IBoxLaunchRouterV2'],
];
const inspect = (path) => JSON.parse(execFileSync('forge', ['inspect', path, 'abi', '--json', '--offline'], { cwd, encoding: 'utf8' }));
const exported = (name, abi) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
const old = readFileSync(target, 'utf8');
const header = old.slice(old.indexOf("import { parseAbiParameters"), old.indexOf('export const '));
const footer = old.slice(old.indexOf('const one ='));
if (!footer.startsWith('const one =')) throw new Error('ABI parameter helper missing');
let code = '// Generated by regenerate-abi-v2.mjs with forge inspect (solc 0.8.26).\n' + header;
for (const [name, source] of shapes) code += exported(name, inspect(`src/box-v2/interfaces/${source}`));
// The vault pays failed hidden-item principal in T; its causal event is implementation-only.
code += exported('vaultV2ExtraEventsAbi', inspect('src/box-v2/BoxVaultV2.sol:BoxVaultV2')
  .filter((item) => item.type === 'event' && item.name === 'FailureItemPaid'));
// The coordinator's claim transfer event is implementation-only; keep its interface ABI frozen.
code += exported('coordinatorV2ExtraEventsAbi', inspect('src/box-v2/BoxCoordinatorV2.sol:BoxCoordinatorV2')
  .filter((item) => item.type === 'event' && item.name === 'ClaimsForwarded'));
// M2 implementations add operational events beyond their frozen interfaces.
for (const [name, source] of [
  ['feeModuleDirectoryV21Abi', 'FeeModuleDirectoryV21'],
  ['receiverV2ExtensionAbi', 'BoxReceiverV2Extension'],
  ['itemLedgerV2Abi', 'ItemLedgerV2'], ['pileVaultV2Abi', 'PileVaultV2'],
  ['holderLedgerV2Abi', 'HolderLedgerV2'], ['holderTokenV2Abi', 'BoxTokenV2Ledger'],
  ['shopVaultV2Abi', 'ShopVaultV2'], ['starterSetLoaderV2Abi', 'StarterSetLoaderV2'],
]) code += exported(name, inspect(`src/box-v2/${source}.sol:${source}`));
for (const [name, source] of [['receiverV2ErrorsAbi', 'BoxReceiverV2'], ['coordinatorV2ErrorsAbi', 'BoxCoordinatorV2']]) {
  code += exported(name, inspect(`src/box-v2/${source}.sol:${source}`).filter((i) => i.type === 'error'));
}
const generated = code + footer;
if (process.argv.includes('--check')) {
  if (old !== generated) {
    console.error('abi-v2.ts is stale; run node packages/chain/src/core/v2/regenerate-abi-v2.mjs');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, generated);
}
