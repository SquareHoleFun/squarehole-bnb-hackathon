// Run the Forge fixture first; capture its real reverts/event plus the default-profile simulation runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { decodeAbiParameters, decodeEventLog, parseAbi, parseAbiParameters, toEventSelector } from 'viem';

const artifact = JSON.parse(readFileSync('packages/contracts/out/CreatorEntitlementV2.sol/CreatorEntitlementV2.json', 'utf8'));
const code = artifact.deployedBytecode.object;
if (!/^0x[0-9a-f]+$/i.test(code)) throw new Error('missing quote runtime');
const generated = `// Generated by packages/indexer/test/core/v2-claims/capture-creator-quote.mjs.\n// Source: CreatorEntitlementV2.sol; solc 0.8.26, Cancun, optimizer 1000, no metadata hash.\nexport const creatorQuoteCodeV2 = '${code}' as const;\n`;
const captured = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const named = parseAbi(['event log_named_bytes(string key, bytes val)']);
const output = {};
for (const suite of Object.values(captured)) for (const result of Object.values(suite.test_results)) {
  if (result.status !== 'Success') throw new Error('fixture contract failed');
  for (const log of result.logs) {
    let value;
    try { value = decodeEventLog({ abi: named, topics: log.topics, data: log.data }).args; } catch { continue; }
    if (value.key === 'redirected') {
      const [logs] = decodeAbiParameters(parseAbiParameters('(bytes32[] topics,bytes data,address emitter)[]'), value.val);
      const matches = logs.filter(l => l.topics[0] === toEventSelector('CreatorClaimed(address,address,address,uint256)'));
      if (matches.length !== 1) throw new Error('missing redirect receipt');
      output.redirected = matches[0];
    } else {
      const [wallet, receiver, asset, data] = decodeAbiParameters(parseAbiParameters('address,address,address,bytes'), value.val);
      output[value.key] = { wallet, receiver, asset, data };
    }
  }
}
if (Object.keys(output).sort().join() !== 'blocked,inexact,native,paused,redirected') throw new Error('missing quote fixtures');
for (const [path, contents] of [
  ['packages/indexer/src/core/v2/claims-quote-code.ts', generated],
  ['packages/indexer/test/core/v2-claims/creator-quote.json', `${JSON.stringify(output, null, 2)}\n`],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== contents) throw new Error(`fixture drift: ${path}`);
  } else writeFileSync(path, contents);
}
