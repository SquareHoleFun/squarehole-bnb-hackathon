/**
 * Cloudflare Pages middleware for the landing page: one canonical host.
 *
 * - squarehole.fun is served (the static files in ../public).
 * - Every other host that reaches the project (www.squarehole.fun, squarehole.xyz, www.squarehole.xyz, squarehole.fit,
 *   www.squarehole.fit, squarehole.pages.dev and its preview hosts) answers 301 to https://squarehole.fun with the
 *   same path and query.
 * - Local hosts (localhost, 127.0.0.1, [::1]) are served too, so `wrangler pages dev` shows the page instead of
 *   bouncing to the live site. Cloudflare only routes a project's own domains to it, so these never arrive in
 *   production.
 *
 * Served responses also get the security headers of public/_headers. Cloudflare's docs say `_headers` does not apply
 * to responses generated by Pages Functions; setting the same values here keeps the policy whichever way that reads for
 * a static file passed through `next()`. test/site.test.js keeps this list and public/_headers equal.
 */

export const CANONICAL_HOST = 'squarehole.fun';

// The five custom-domain aliases shared with the droplet. Pages/preview and unknown hosts still redirect below.
export const REDIRECT_HOSTS = Object.freeze([
  'www.squarehole.fun',
  'squarehole.xyz',
  'www.squarehole.xyz',
  'squarehole.fit',
  'www.squarehole.fit',
]);

const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1', '[::1]']);

const NULL_BODY_STATUSES = new Set([204, 205, 304]);

/** How long browsers may keep the redirect (a day), so a domain can still be repurposed later. */
const REDIRECT_CACHE = 'public, max-age=86400';

export const SECURITY_HEADERS = Object.freeze({
  'Content-Security-Policy':
    "default-src 'none'; img-src 'self'; style-src 'self'; font-src 'self'; manifest-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'Strict-Transport-Security': 'max-age=86400',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'no-referrer',
  'Permissions-Policy':
    'accelerometer=(), browsing-topics=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
});

/**
 * Where a request should be redirected, or null when it is served here. The target is built by joining strings onto a
 * fixed origin, never by resolving the path against it, so a path such as `//example.com` stays a path.
 * @param {string} requestUrl
 * @returns {string | null}
 */
export function redirectTarget(requestUrl) {
  const url = new URL(requestUrl);
  if (url.hostname === CANONICAL_HOST || LOCAL_HOSTS.has(url.hostname)) return null;
  return `https://${CANONICAL_HOST}${url.pathname}${url.search}`;
}

/**
 * @param {{ request: Request, next: () => Promise<Response> }} context
 * @returns {Promise<Response>}
 */
export async function onRequest(context) {
  const target = redirectTarget(context.request.url);
  if (target !== null) {
    return new Response(null, { status: 301, headers: { Location: target, 'Cache-Control': REDIRECT_CACHE } });
  }
  const response = await context.next();
  // A copy, because the response next() returns may have immutable headers. Statuses such as 304 (a browser's cache
  // check) must not carry a body, or the Response constructor throws.
  const served = new Response(NULL_BODY_STATUSES.has(response.status) ? null : response.body, response);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) served.headers.set(name, value);
  return served;
}
