/** T02's shared producer boundary. Import generators; never rewrite their reviewed manifests or samples. */
import assert from 'node:assert/strict';
import { reviewedManifestForPlatform } from './bag-holders-normal-zero-platform-exception.mjs';
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, mkdtempSync, readFileSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const definition = (count, modelPolicy, seed, columns) => Object.freeze({ count, modelPolicy, seed, columns: Object.freeze(columns) });
export const UNIQUE_KITS = Object.freeze({
  'rent-free': definition('500', '3d', 'Rent Free / 500 little houses / no spare keys / proposal 1', ['house', 'door', 'window', 'post', 'plant', 'step']),
  'bag-holders': definition('420', '3d', 'Bag Holders / every bag is held / proposal 1 / 2026-10-27', ['kind', 'trim', 'repair', 'tag', 'stitch']),
  'link-marines-v2': definition('420', '2d', 'Link Marines / mess night / same ration / proposal 1', ['Rank', 'Squad', 'Face', 'Eyes', 'Grooming', 'Collar', 'Mouth', 'Prop', 'Wall']),
  'exit-liquidity': definition('404', '2d', 'exit-liquidity/404-signs/no-way-out/v1', ['sign', 'housing', 'route', 'repair', 'equipment', 'conduit']),
});
const producers = {
  'rent-free': () => import('../../examples/boxes/rent-free/unique/build.mjs'),
  'bag-holders': () => import('../../examples/boxes/bag-holders/unique/build.mjs'),
  'link-marines-v2': () => import('../../examples/boxes/link-marines-v2/unique/build.mjs'),
  'exit-liquidity': () => import('../../examples/boxes/exit-liquidity/unique/build.mjs'),
};
const policyFor = id => {
  assert.ok(Object.hasOwn(UNIQUE_KITS, id), 'choose a supported unique kit');
  return UNIQUE_KITS[id];
};
const digest = bytes => `0x${createHash('sha256').update(bytes).digest('hex')}`;
const json = path => JSON.parse(readFileSync(path, 'utf8'));

/**
 * Normalize producer records without sorting or repairing them. Every id must already be ordered 1..N.
 * Bare producer SHA-256 becomes app 0x hex ONLY here. Filenames are derived from validated ids; a producer's
 * explicit file field must agree exactly. Review models remain here even for 2D, so verification checks them too.
 */
export function normalizeUniqueManifest(id, manifest) {
  const policy = policyFor(id);
  assert.equal(manifest.count, policy.count, 'unique count');
  assert.equal(manifest.seed, policy.seed, 'fixed unique seed');
  const rows = id === 'rent-free' ? manifest.entries : manifest.items;
  assert.ok(Array.isArray(rows), 'unique items required');
  assert.equal(BigInt(rows.length), BigInt(policy.count), 'complete unique edition required');
  const asset = (record, file) => {
    assert.ok(record && typeof record === 'object', 'asset record required');
    assert.match(record.sha256, /^[0-9a-f]{64}$/, 'bare manifest sha256 required');
    assert.ok(Number.isSafeInteger(record.bytes) && record.bytes > 0 && record.bytes <= 1_048_576, 'one raw block per asset');
    if (record.file !== undefined) assert.equal(record.file, file, 'safe generated filename required');
    return { file, sha256: `0x${record.sha256}`, bytes: record.bytes };
  };
  const items = rows.map((row, index) => {
    assert.equal(row.id, String(index + 1), 'unique items must be ordered 1..N');
    assert.ok(row.traits && typeof row.traits === 'object' && !Array.isArray(row.traits), 'full traits required');
    assert.deepEqual(Object.keys(row.traits).sort(), [...policy.columns].sort(), 'complete unique traits required');
    for (const value of Object.values(row.traits)) assert.ok(typeof value === 'string' && /^[\x20-\x21\x23-\x5b\x5d-\x7e]{1,255}$/.test(value), 'on-chain trait text required');
    return {
      id: row.id, traits: Object.fromEntries(policy.columns.map(key => [key, row.traits[key]])),
      picture: asset(row.picture, `picture-${row.id}.png`),
      model: asset(row.model, `model-${row.id}.glb`),
      ...(row.svg ? { svg: asset(row.svg, `picture-${row.id}.svg`) } : {}),
    };
  });
  assert.equal(new Set(items.map(item => item.picture.sha256)).size, items.length, 'every picture must be unique');
  return { ...policy, items };
}

/**
 * THE public interface: { count (decimal string), seed, columns, modelPolicy, directory, items }.
 * items are ordered 1..N: { id (decimal string), traits (all columns), picture: { path, sha256, bytes },
 * model: null | { path, sha256, bytes } }. Only rent-free/bag-holders expose a model. Both asset kinds are
 * exact generated bytes, one SHA-256 raw block each. Paths are local inputs, never part of the public list.
 * Validation always compares against the repository's reviewed manifest, not a caller-supplied substitute.
 */
export function verifyUniqueSet(id, directory) {
  policyFor(id);
  const reviewed = reviewedManifestForPlatform(id, json(resolve(ROOT, 'examples/boxes', id, 'unique/manifest.json')));
  const generated = json(resolve(directory, 'manifest.json'));
  const normalized = normalizeUniqueManifest(id, generated);
  assert.deepEqual(generated, reviewed, 'generated manifest differs from reviewed manifest');
  const base = realpathSync(directory);
  const checked = asset => {
    const path = resolve(base, asset.file);
    assert.ok(lstatSync(path).isFile() && realpathSync(path) === path, 'regular generated file required; no symlinks');
    const bytes = readFileSync(path);
    assert.equal(digest(bytes), asset.sha256, `${asset.file} sha256 differs from reviewed manifest`);
    assert.equal(bytes.length, asset.bytes, `${asset.file} byte length differs`);
    return { path, sha256: asset.sha256, bytes: asset.bytes };
  };
  return { ...UNIQUE_KITS[id], directory: base, items: normalized.items.map(item => {
    const picture = checked(item.picture), model = checked(item.model);
    if (item.svg) checked(item.svg);
    return { id: item.id, traits: item.traits, picture, model: normalized.modelPolicy === '3d' ? model : null };
  }) };
}

/** Run the existing producer at its fixed seed, under the pinned toolchain, into a fresh ignored directory. */
export async function buildUniqueSet(id) {
  policyFor(id);
  assert.equal(process.versions.node, '24.22.1', 'use Node 24.22.1');
  const require = createRequire(new URL('../../packages/cards/package.json', import.meta.url));
  assert.equal(require('@resvg/resvg-js/package.json').version, '2.6.2', 'use pinned resvg 2.6.2');
  const parent = resolve(ROOT, '.cache/tmp');
  mkdirSync(parent, { recursive: true });
  const directory = mkdtempSync(resolve(parent, `kits-unique-${id}-`));
  const producer = await producers[id]();
  await producer.build(directory);
  return verifyUniqueSet(id, directory);
}
